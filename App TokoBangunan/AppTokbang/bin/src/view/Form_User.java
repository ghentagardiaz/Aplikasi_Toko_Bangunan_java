    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:
        if(idUser == 0){
            JOptionPane.showMessageDialog(null,"Pilih data terlebih dahulu");
            return;
    }
        int jawab = JOptionPane.showConfirmDialog(null,"Yakin hapus data?","Konfirmasi",JOptionPane.YES_NO_OPTION);
        if(jawab == JOptionPane.YES_OPTION){            
            dao.hapusData(idUser);
            tampilData();
            idUser = 0;
            txtUsername.setText("");
            txtPassword.setText("");
        }
    }//GEN-LAST:event_btnHapusActionPerformed

    private void tblUserMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblUserMouseClicked
        // TODO add your handling code here:
        int row = tblUser.getSelectedRow();

        idUser = Integer.parseInt(tblUser.getValueAt(row, 0).toString());
        txtUsername.setText(tblUser.getValueAt(row, 1).toString());
        txtPassword.setText(tblUser.getValueAt(row, 2).toString());
    }//GEN-LAST:event_tblUserMouseClicked

    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        if(txtUsername.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(null,"Username tidak boleh kosong");
            return;
    }

        if(txtPassword.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(null,"Password tidak boleh kosong");
            return;
    }

        Model_User user = new Model_User();
        user.setUsername(txtUsername.getText());
        user.setPassword(txtPassword.getText());

        if(idUser == 0){
            dao.tambahData(user);
            JOptionPane.showMessageDialog(null,"Data berhasil ditambah");
        }else{
            user.setIdUser(idUser);
            dao.ubahData(user);

            JOptionPane.showMessageDialog(null,"Data berhasil diubah");
    }

        tampilData();
        txtUsername.setText("");
        txtPassword.setText("");

        idUser = 0;

        CardLayout cl = (CardLayout) getLayout();
        cl.show(this, "card2");
    }//GEN-LAST:event_btnSimpanActionPerformed

