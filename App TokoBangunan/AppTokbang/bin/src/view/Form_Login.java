    private void prosesLogin(){
        if(validasiInput()==true){
            String id = t_username.getText();
            String user = t_username.getText();
            String pass = String.valueOf(t_password.getPassword());
            
            model.Model_Login mod_log = new Model_Login();
            
            mod_log.setId_user(id);
            mod_log.setUsername(user);
            mod_log.setPass_user(pass);

            servis.prosesLogin(mod_log);
            if(tutup){
                dispose();
        }
    }
}
    private boolean validasiInput(){

    if(t_username.getText().trim().isEmpty() || t_username.getText().equals("Username")){
        JOptionPane.showMessageDialog(null,"Username tidak boleh kosong");
        return false;
    }

    String pass = String.valueOf(t_password.getPassword());
        if(pass.isEmpty()|| pass.equals("Password")){
            JOptionPane.showMessageDialog(null,"Password tidak boleh kosong");
            return false;
        }

            return true;
    } 
