    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        if(txtNamaSupplier.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(null,"Nama supplier tidak boleh kosong");
            return;
    }
    Model_Supplier ms = new Model_Supplier();
        ms.setNamaSupplier(txtNamaSupplier.getText());
        ms.setAlamat(txtAlamatSupplier.getText());
        ms.setTelepon(txtNoTelepon.getText());

        if(idSupplier == 0){
            dao.tambahData(ms);
            JOptionPane.showMessageDialog(null,"Data berhasil ditambah");
        }else{
            ms.setIdSupplier(idSupplier);
            dao.ubahData(ms);
            JOptionPane.showMessageDialog(null,"Data berhasil diubah");
    }
        tampilData();
        idSupplier = 0;
        CardLayout cl = (CardLayout) getLayout(); 
        cl.show(this, "data");
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:
        if(idSupplier == 0){
            JOptionPane.showMessageDialog(null, "Pilih data terlebih dahulu");
            return;
        }
        int jawab = JOptionPane.showConfirmDialog(null, "Yakin hapus data?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
        if(jawab == JOptionPane.YES_OPTION){
            dao.hapusData(idSupplier);
            tampilData();
            idSupplier = 0;
        }
    }//GEN-LAST:event_btnHapusActionPerformed


