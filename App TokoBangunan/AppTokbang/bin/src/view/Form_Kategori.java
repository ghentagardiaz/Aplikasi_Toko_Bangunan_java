    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // TODO add your handling code here:
        if(txtNamaKategori.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(null, "Nama kategori tidak boleh kosong");
            return;
    }
    Model_Kategori mk = new Model_Kategori();
    mk.setNamaKategori(txtNamaKategori.getText());
   
    if(idKategori == 0){dao.tambahData(mk);
    JOptionPane.showMessageDialog(null,"Data berhasil ditambah");

    }else{
        mk.setIdKategori(idKategori);
        dao.ubahData(mk);
        JOptionPane.showMessageDialog(null,"Data berhasil diubah");
    }
    tampilData();
    txtNamaKategori.setText("");
    idKategori = 0;
    pnInputKategori.setVisible(false);
    pnKategori.setVisible(true);
    }//GEN-LAST:event_btnSimpanActionPerformed

