    private void tampilData(){

    DefaultTableModel model =
            new DefaultTableModel();

    model.addColumn("ID");
    model.addColumn("Nama Kategori");

    List<Model_Kategori> list =
            dao.getData();

    for(Model_Kategori mk : list){

        model.addRow(new Object[]{
            mk.getIdKategori(),
            mk.getNamaKategori()
        });

    }

    tblKategori.setModel(model);
}

