    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        // TODO add your handling code here:
        int baris =tblBarangMasuk.getSelectedRow();
        if (baris == -1) {
            javax.swing.JOptionPane.showMessageDialog(null,"Pilih data terlebih dahulu!");
            return;
    }
        int id =
            Integer.parseInt(tblBarangMasuk.getValueAt(baris, 0).toString());
            dao.hapusData(id);
            tampilData();
            javax.swing.JOptionPane.showMessageDialog(null,"Data berhasil dihapus");
    }//GEN-LAST:event_btnHapusActionPerformed


