    private void isiTanggal() {
        SimpleDateFormat sdf =new SimpleDateFormat("yyyy-MM-dd");
        txtTanggal.setText(sdf.format(new Date()));
        txtTanggal.setEditable(false);
    }
    
    private void loadBarang() {
        cbBarang.removeAllItems();
        List<Model_Barang> list = daoBarang.getData();
        for (Model_Barang barang : list) {
        cbBarang.addItem(barang);
        }
    }
    
    private void tampilData() {
    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("ID");
    model.addColumn("Tanggal");
    model.addColumn("Barang");
    model.addColumn("Jumlah");
    model.addColumn("Harga Beli");
    model.addColumn("Subtotal");

    List<Model_BarangMasuk> list = dao.getData();

    for (Model_BarangMasuk bm : list) {

        model.addRow(new Object[]{
            bm.getIdMasuk(),
            bm.getTanggal(),
            bm.getNamaBarang(),
            bm.getJumlah(),
            bm.getHargaBeli(),
            bm.getSubtotal()
            });
        }

    tblBarangMasuk.setModel(model);
    }
    
    private void bersihForm() {
        txtJumlah.setText("");
        txtHargaBeli.setText("");
        isiTanggal();
        if (cbBarang.getItemCount() > 0) {
            cbBarang.setSelectedIndex(0);
        }
    }
    
    private void simpanData() {
        try {
            Model_Barang barang =(Model_Barang) cbBarang.getSelectedItem();
            int jumlah =Integer.parseInt(txtJumlah.getText());
            double hargaBeli =  Double.parseDouble( txtHargaBeli.getText());
            double subtotal =jumlah * hargaBeli;

            Model_BarangMasuk bm =new Model_BarangMasuk();
            SimpleDateFormat sdf =new SimpleDateFormat("yyyy-MM-dd");
            bm.setTanggal(sdf.parse(txtTanggal.getText()));
            bm.setIdBarang(barang.getIdBarang());
            bm.setJumlah(jumlah);
            bm.setHargaBeli(hargaBeli);
            bm.setSubtotal(subtotal);
            dao.tambahData(bm);
            tampilData();
            bersihForm();
            CardLayout cl =(CardLayout) getLayout();
            cl.show(this, "data");
            javax.swing.JOptionPane.showMessageDialog(null,"Data berhasil disimpan");

        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null,"Gagal menyimpan data : "+ e.getMessage());
            e.printStackTrace();
        }
    }

